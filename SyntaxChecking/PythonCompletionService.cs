        private readonly List<ICompletionData> _completions;

        public PythonCompletionService()
        {
            _completions = new List<ICompletionData>();
            AddRange(Keywords, "Ключевое слово");
            AddRange(BuiltIns, "Встроенная функция");
            AddRange(Exceptions, "Исключение");
            AddRange(MagicMethods, "Магический метод");
        }

        private void AddRange((string Word, string Description, string Type)[] items, string defaultType)
        {
            foreach (var item in items)
            {
                _completions.Add(new BslCompletionData(item.Word, item.Description, item.Type ?? defaultType));
            }
        }

        public List<ICompletionData> GetCompletions(string word)
        {
            if (string.IsNullOrEmpty(word))
                return _completions;

            return _completions
                .Where(c => c.Text.StartsWith(word, System.StringComparison.OrdinalIgnoreCase))
                .ToList();
        }
